  ~base
  name varchar [note: 'Алиас из регламента']
  Records {
    1, '2026-11-11', '2026-11-11', "вилка А-101"
    2, '2026-11-11', '2026-11-11', "вилка А-102"
    3, '2026-11-11', '2026-11-11', "кнопка B-301"
  }
}

-- Действие (заполняет LLM)
Table actions {
  ~base
  name varchar [note: 'Название единицы действия']
  Records {
    1, '2026-11-11', '2026-11-11', "взять"
    2, '2026-11-11', '2026-11-11', "вставить"
    3, '2026-11-11', '2026-11-11', "нажать"
  }
}

-- Шаги (заполняет LLM)
