Table steps {
  ~base
  action_id guid [ref: > actions.id, not null]
  object_id guid [ref: > objects.id, not null]
  Records {
    1, '2026-11-11', '2026-11-11', 1, 1
    2, '2026-11-11', '2026-11-11', 2, 1
    3, '2026-11-11', '2026-11-11', 3, 3
  }
}

-- Сценарии_шаги (многие-ко-многим, заполняет LLM)
Table scenarios_steps {
  ~base
  scenario_id guid [ref: > scenarios.id, not null]
  step_id guid [ref: > steps.id, not null]
  order int [note: 'Порядок шага в сценарии']
  Records {
    1, '2026-11-11', '2026-11-11', 1, 1, 1
    2, '2026-11-11', '2026-11-11', 1, 2, 2
    3, '2026-11-11', '2026-11-11', 1, 3, 3
  }
}

/*
 * Для вводимых пользователем файлов нужно использовать S3-совместимое хранилище, в чате хранить ссылку/id на него.
 * В случае с документами, которые были в файловом хранилище при создании эмбеддингов, используются "парсеры",
 * которые извлекают смысл из содержимого документа, это превращается в чанки и отправляется в векторную БД.
*/

-- Сценарии (заполняет LLM)
Table scenarios {
  ~base
  parent_scenario_id guid [ref: > scenarios.id] [note: 'Может быть null, если корень.']
  user_request text [note: 'Запрос пользователя + чанки эмбеддингов и ссылки на файлы']
  llm_context json [note: 'Ответ LLM']
  child_count int [note: 'Число обратных ссылок; для удаления']
  Records {
    1, '2026-11-11', '2026-11-11', null, "...", "...", 1
  }
}

/*
 * Если два человека зашли в одну уже существующую сессию, то каждый создаст свой запрос,
 * и к последнему запросу будут ссылаться два разных запроса.
*/

-- Пользовательские сессии: ссылка на ноду/лист в дереве/коммит запроса (типо HEAD в Git).
Table sessions {
  ~base
  scenario_id guid [ref: - scenarios.id, not null]
  course_name varchar [note: 'Название курса']
  Records {
    1, '2026-11-11', '2026-11-11', 1, "..."
  }
}

-- Шаблон базовых полей
TablePartial base {
  id guid [pk]
  created_at timestamp [default: `now()`]
  updated_at timestamp [default: `now()`]
  is_deleted boolean [default: false] [note: 'Для мягкого удаления']
}
